const samplePlan = () => ({
  dirs: ["3dmodels", "textures", "scripts"],
  files: [
    { path: "athena.ini", text: 'default_script = "main.js"\n' },
    { path: "3dmodels/player.obj", text: "o Player\n" },
    { path: "scripts/TopDownController.js", text: "export function init(ctx) {}\n" },
    { path: "mygame.athena.json", text: '{"name":"MyGame"}' },
  ],
});

Deno.test("scaffolding creates the directories and writes every planned file", async () => {
  const { root, files, dirs } = mockDir("newgame");
  const out = await A.fsScaffoldProject(root, samplePlan());

  for (const d of ["3dmodels/", "textures/", "scripts/"]) {
    assert(dirs.has(d), `${d} was not created`);
  }
  assertEquals(out.skipped, []);
  assertEquals(out.written.length, 4);
  assertEquals(files.get("mygame.athena.json"), '{"name":"MyGame"}');
});

Deno.test("an empty asset directory is still created", async () => {
  // textures/ has no files in the plan. Without it the folder layout is
  // incomplete and os.chdir("textures") fails on hardware.
  const { root, dirs } = mockDir("newgame");
  await A.fsScaffoldProject(root, samplePlan());
  assert(dirs.has("textures/"));
});

Deno.test("scaffolding never overwrites a file that is already there", async () => {
  const { root, files } = mockDir("existinggame", {
    "athena.ini": "# my own settings\n",
    "3dmodels/player.obj": "o MyRealCharacter\n",
  });
  const out = await A.fsScaffoldProject(root, samplePlan());

  assertEquals(out.skipped, ["athena.ini", "3dmodels/player.obj"]);
  assertEquals(files.get("athena.ini"), "# my own settings\n", "an existing ini was replaced");
  assertEquals(files.get("3dmodels/player.obj"), "o MyRealCharacter\n", "real art was replaced");
  assert(files.has("scripts/TopDownController.js"), "the rest of the scaffold was skipped too");
});

Deno.test("the runtime is copied in as athena.elf", async () => {
  const { root, files } = mockDir("newgame");
  const data = new Uint8Array([0x7f, 0x45, 0x4c, 0x46]);   // ELF magic
  const out = await A.fsScaffoldProject(root, samplePlan(), { name: "athena.elf", data });

  assert(out.written.includes("athena.elf"));
  assert(files.has("athena.elf"));
});

Deno.test("an existing runtime is left alone", async () => {
  const { root, files } = mockDir("newgame", { "athena.elf": "existing" });
  const out = await A.fsScaffoldProject(root, samplePlan(), { name: "athena.elf", data: new Uint8Array([1]) });
  assert(out.skipped.includes("athena.elf"));
  assertEquals(files.get("athena.elf"), "existing");
});

Deno.test("a scaffold with no runtime still lays the folder out", async () => {
  const { root, files } = mockDir("newgame");
  const out = await A.fsScaffoldProject(root, samplePlan(), null);
  assert(!files.has("athena.elf"));
  assertEquals(out.written.length, 4, "the rest of the scaffold should still be written");
});

Deno.test("emptiness is reported so the caller can warn before scaffolding", async () => {
  assertEquals(await A.fsIsEmpty(mockDir("fresh").root), true);
  assertEquals(await A.fsIsEmpty(mockDir("used", { "main.js": "// game\n" }).root), false);
});

