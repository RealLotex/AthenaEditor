import {load,shutdown} from '../tests/_load.js';
try {
  const A=await load(),data=await A.bakeWaterMotion();
  if(A.WATER_MOTION_DATA.previousFrames&&A.WATER_MOTION_DATA.previousLevels){data.previousFrames=A.WATER_MOTION_DATA.previousFrames;data.previousLevels=A.WATER_MOTION_DATA.previousLevels;}
  else {
    const result=await new Deno.Command('git',{args:['show','26a5b47:src/core/water-data.js']}).output();if(!result.success)throw Error('Previous shipped water is unavailable for safe migration.');
    const source=new TextDecoder().decode(result.stdout),previous=JSON.parse(source.slice(source.indexOf('{'),source.lastIndexOf('}')+1));
    data.previousFrames=previous.frames.map(frame=>A.waterFrameFingerprint(frame.dataUrl));
    data.previousLevels=Object.fromEntries(Object.entries(previous.levels).map(([size,list])=>[size,list.map(frame=>A.waterFrameFingerprint(frame.dataUrl))]));
  }
  await Deno.writeTextFile('src/core/water-data.js','// Generated by tools/generate-water.js. Smooth periodic ripples, native T4.\nconst WATER_MOTION_DATA = '+JSON.stringify(data)+';\n');
  console.log('Prepared '+data.frames.length+' seamless water frames with one palette and safe legacy fingerprints.');
} finally {await shutdown();}
