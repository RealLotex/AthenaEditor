// Pack authored 360° panoramas offline; no image service is needed to rebuild.
// deno run -A tools/generate-skyboxes.js
import { PNG } from "npm:pngjs@7.0.0";
import { Buffer } from "node:buffer";
import { load, shutdown } from "../tests/_load.js";

const A = await load();
const root = new URL("../", import.meta.url);
try {
  const images = {}, highImages = {}, highOnly = Deno.args.includes("--high-only");
  for (const preset of A.SKYBOX_PRESETS) {
    const bytes = await Deno.readFile(new URL(`assets/skyboxes/${preset.id}.png`, root));
    const source = PNG.sync.read(Buffer.from(bytes));
    if (Math.abs(source.width / source.height - 2) > .01) throw Error(`${preset.id}: expected a full-sphere 2:1 panorama.`);
    if (source.width < A.SKYBOX_WIDTH || source.height < A.SKYBOX_HEIGHT) throw Error(`${preset.id}: the source must supply the library preview without enlargement.`);
    // Preserve every source texel at the GS's maximum RGB555 precision.
    // Never resize first or use a paletted preview as the source.
    const rgb = new Uint8Array(source.width * source.height * 3);
    for (let y = 0; y < source.height; y++) for (let x = 0; x < source.width; x++) for (let c = 0; c < 3; c++) {
      const i = y * source.width + x;
      rgb[i * 3 + c] = (source.data[i * 4 + c] >> 3) - (x ? source.data[(i - 1) * 4 + c] >> 3 : 0);
    }
    const compressed = new Uint8Array(await new Response(new Blob([rgb]).stream().pipeThrough(new CompressionStream("deflate"))).arrayBuffer());
    highImages[preset.id] = { width: source.width, height: source.height, encoding: "rgb555-delta", rgb: A.bytesDataURL(compressed).split(",")[1] };
    if (highOnly) { console.log(`${preset.id}: original ${source.width} × ${source.height}, RGB555`); continue; }
    const image = A.resizeTexturePixels(source, A.SKYBOX_WIDTH, A.SKYBOX_HEIGHT);
    const { width, height, data } = image;
    // Smooth a narrow longitude band; equal edge texels also protect native
    // sphere sampling at its UV seam.
    for (let y = 0; y < height; y++) {
      const left = y * width * 4, right = left + (width - 1) * 4;
      const seam = [0, 1, 2].map(k => (data[left + k] + data[right + k]) / 2);
      for (let x = 0; x < 16; x++) {
        const amount = (1 - x / 16) ** 2;
        for (const at of [left + x * 4, right - x * 4]) for (let k = 0; k < 3; k++) data[at + k] = Math.round(data[at + k] * (1 - amount) + seam[k] * amount);
      }
    }
    // All longitudes converge at the poles; a few rows avoid pinched seams.
    for (const pole of [0, height - 1]) {
      const color = [0, 1, 2].map(k => {
        let sum = 0; for (let x = 0; x < width; x++) sum += data[(pole * width + x) * 4 + k];
        return sum / width;
      });
      for (let row = 0; row < 8; row++) {
        const y = pole === 0 ? row : height - 1 - row, amount = (1 - row / 8) ** 2;
        for (let x = 0; x < width; x++) for (let k = 0; k < 3; k++) {
          const at = (y * width + x) * 4 + k; data[at] = Math.round(data[at] * (1 - amount) + color[k] * amount);
        }
      }
    }
    for (let at = 3; at < data.length; at += 4) data[at] = 255;
    // T8 consumes ~512 KB + CLUT at twice the old RGBA dimensions.
    const output = await A.indexedTexturePNG(A.quantizeTexture(image, 256));
    images[preset.id] = A.bytesDataURL(output);
    console.log(`${preset.id}: ${width} × ${height}, ${output.length} bytes, T8`);
  }
  if (!highOnly) await Deno.writeTextFile(new URL("src/core/skybox-data.js", root), "// Generated by tools/generate-skyboxes.js from assets/skyboxes.\nconst SKYBOX_PRESET_IMAGES = " + JSON.stringify(images, null, 2) + ";\n");
  await Deno.writeTextFile(new URL("src/core/skybox-high-data.js", root), "// Original-resolution RGB555 panoramas, packed losslessly at maximum native precision.\nconst SKYBOX_PRESET_HIGH_IMAGES = " + JSON.stringify(highImages, null, 2) + ";\n");
} finally { await shutdown(); }
